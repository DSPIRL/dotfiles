#!/usr/bin/env bash
# Isolated palette/CLI/parser checks. No theme switch, clipboard, or launcher action.
set -euo pipefail
root=$(cd "$(dirname "$0")/.." && pwd)
sandbox=$(mktemp -d)
trap 'rm -rf "$sandbox"' EXIT
export HOME="$sandbox/home with spaces" XDG_CONFIG_HOME="$sandbox/home with spaces/.config"
export XDG_STATE_HOME="$sandbox/state with spaces" XDG_CACHE_HOME="$sandbox/cache"
mkdir -p "$HOME/.config/rofi" "$HOME/.config/hypr/scripts" "$XDG_STATE_HOME/hypr/effects" "$sandbox/bin"
cp -a "$root/dot_config/rofi/." "$HOME/.config/rofi/"
cp "$root/dot_config/rofi/wallust/colors-rofi.rasi.tmpl" "$HOME/.config/rofi/wallust/colors-rofi.rasi"
cp "$root/dot_config/hypr/scripts/executable_toggle-breeze-theme.sh" "$HOME/.config/hypr/scripts/toggle-breeze-theme.sh"
chmod +x "$HOME/.config/hypr/scripts/toggle-breeze-theme.sh"
cat >"$sandbox/bin/hyprctl" <<'MOCK'
#!/usr/bin/env bash
case "$1" in repl) printf 'effects-applied\n' ;; configerrors) ;; *) exit 2 ;; esac
MOCK
printf '#!/bin/sh\nexit 1\n' >"$sandbox/bin/pgrep"
chmod +x "$sandbox/bin"/*
export PATH="$sandbox/bin:$PATH"
palette="$HOME/.config/rofi/wallust/colors-rofi.rasi"
refresh() { bash "$root/dot_config/hypr/scripts/executable_toggle-breeze-theme.sh" refresh-shell; }
cli() { bash "$root/dot_config/hypr/scripts/executable_desktop-settings.sh" "$@"; }
value() { awk -v key="$1:" '$1 == key {gsub(/;/,"",$2); print $2; exit}' "$palette"; }
expect() { [[ $(value "$1") == "$2" ]] || { printf 'Unexpected %s: %s\n' "$1" "$(value "$1")" >&2; exit 1; }; }

# Import the existing wallpaper accent once, then preserve its opaque source token.
printf '* {\n selected-background: #345678;\n}\n' >"$palette"
printf 'dark\n' >"$XDG_STATE_HOME/hypr/breeze-theme"
printf 'disabled\n' >"$XDG_STATE_HOME/hypr/effects/low-effects"
settings_hash=$(sha256sum "$HOME/.config/rofi/appearance.rasi")
refresh
expect accent '#345678'
expect selected-background '#34567838'
expect window-background '#30374666'
expect normal-text '#F4F6FC'
refresh
expect accent '#345678'
printf 'light\n' >"$XDG_STATE_HOME/hypr/breeze-theme"
refresh
expect window-background '#FFFFFF66'
expect normal-text '#101827'
expect selected-background '#34567838'
[[ $(sha256sum "$HOME/.config/rofi/appearance.rasi") == "$settings_hash" ]]

# A palette regenerated by Wallust must regain the selected light/dark material.
python3 - "$root" "$palette" <<'PY'
import pathlib, sys
source = pathlib.Path(sys.argv[1], 'dot_config/wallust/templates/colors-rofi.rasi').read_text()
pathlib.Path(sys.argv[2]).write_text(source.replace('{{color12}}', '#456789'))
PY
refresh
expect accent '#456789'
expect window-background '#FFFFFF66'
expect selected-background '#45678938'

# Concurrent refreshes publish complete files, not partial Rasi fragments.
refresh & first=$!
refresh & second=$!
wait "$first"; wait "$second"
expect accent '#456789'
[[ $(tail -n 1 "$palette") == '}' ]]
[[ $(find "$(dirname "$palette")" -name 'colors-rofi.rasi.??????' | wc -l) == 0 ]]

# Existing low-effects controls refresh Rofi without reapplying the desktop theme.
timeout 3 bash "$root/dot_config/hypr/scripts/executable_desktop-settings.sh" low-effects enable
expect window-background '#F0F2F6'
expect window-bottom '#F0F2F6'
expect surface-background '#E2E6ED'
expect selected-background '#CED9E8'
[[ $(<"$XDG_STATE_HOME/hypr/breeze-theme") == light ]]
cli low-effects disable
expect window-background '#FFFFFF66'
# Palette failure must roll the preference back and leave the old file intact.
old=$(sha256sum "$palette")
rm "$palette.lock"
mkdir "$palette.lock"
if cli low-effects enable 2>/dev/null; then echo 'Expected palette failure rollback' >&2; exit 1; fi
[[ $(cli low-effects status) == disabled ]]
[[ $(sha256sum "$palette") == "$old" ]]
rmdir "$palette.lock"
refresh
# Corrupt low-effects state fails solid; corrupt color input is never emitted.
printf 'invalid\n' >"$XDG_STATE_HOME/hypr/effects/low-effects"
refresh
expect window-background '#F0F2F6'
printf '* {\n accent: not-a-color;\n}\n' >"$palette"
refresh
expect accent '#9FC5F0'
printf 'disabled\n' >"$XDG_STATE_HOME/hypr/effects/low-effects"

if command -v rofi >/dev/null; then
  # dump-theme exits successfully even after some parser errors. Check the
  # resolved material/font as well, so a silent fallback cannot count as a pass.
  for mode in dark light; do
    printf '%s\n' "$mode" >"$XDG_STATE_HOME/hypr/breeze-theme"
    refresh
    for config in "$HOME/.config/rofi/"config*.rasi; do
      rofi -config "$config" -dump-theme >"$sandbox/theme.rasi" 2>"$sandbox/parser.log"
      grep -q 'Noto Sans 14px' "$sandbox/theme.rasi"
      grep -q 'window-image:.*linear-gradient' "$sandbox/theme.rasi"
      grep -q 'background-image:.*var(window-image)' "$sandbox/theme.rasi"
      [[ ! -s "$sandbox/parser.log" ]]
      # Every mode must inherit the same top-center anchor, including grids
      # and input-only dialogs whose heights differ from the app launcher.
      python3 - "$sandbox/theme.rasi" <<'PY'
import pathlib, re, sys
text = pathlib.Path(sys.argv[1]).read_text()
window = re.search(r'\bwindow\s*\{([^}]*)\}', text).group(1)
for name, expected in [
    ('location', 'north'), ('anchor', 'north'),
    ('x-offset', r'0(?:\.0+)?(?:px)?'), ('y-offset', r'18(?:\.0+)?%')
]:
    assert re.search(rf'\b{name}:\s*{expected}\s*;', window), (name, window)
PY
      rofi -config "$config" -dump-config >"$sandbox/config.rasi" 2>"$sandbox/parser.log"
      grep -Eq 'hover-select:[[:space:]]+true;' "$sandbox/config.rasi"
      grep -Eq 'me-select-entry:[[:space:]]+"";' "$sandbox/config.rasi"
      grep -Eq 'me-accept-entry:[[:space:]]+"MousePrimary";' "$sandbox/config.rasi"
      [[ ! -s "$sandbox/parser.log" ]]
      if [[ "${config##*/}" == config-apps.rasi ]]; then
        grep -q 'drun-display-format: "{name}"' "$sandbox/config.rasi"
        grep -q 'drun-match-fields: "name,generic,exec,categories,keywords,comment"' "$sandbox/config.rasi"
        grep -Eq 'size:[[:space:]]+42px' "$sandbox/theme.rasi"
        [[ ! -s "$sandbox/parser.log" ]]
      fi
      if [[ "${config##*/}" == config-emoji.rasi ]]; then
        python3 - "$sandbox/theme.rasi" <<'PY'
import pathlib, re, sys
text = pathlib.Path(sys.argv[1]).read_text()
# Grid sizing must use the emoji font too; changing element-text alone clips it.
assert re.search(r'window\s*\{[^}]*font:\s*var\(emoji-font\)', text)
assert re.search(r'entry\s*\{[^}]*font:\s*var\(text-font\)', text)
PY
      fi
    done
  done
else
  echo 'SKIP: Rofi parser checks (rofi unavailable)'
fi
printf 'Rofi theme checks passed: accents, dark/light, atomic refresh, low-effects/rollback, shared placement, and all launcher configs\n'
